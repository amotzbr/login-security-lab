def load_users() -> dict:
    """
    Load the users DB from USES_DB_FILE

    If the file does not exist, returns an empty dict.
    The file is expected to contain a JSON object:
    {
        "username1": {...}
        "username2": {...}
        ...
        "_meta":{
                  "group_seed": "..."
                }
    }
    :return: dict with users' data as loaded from JSON.
    """
    """If file doesnt exists returns {}"""
    if not os.path.exists(USERS_DB_FILE):
        return {}
    with open(USERS_DB_FILE, "r") as f:
        return json.load(f)

def save_users(users_dict:dict, group_seed: str)->None:
    """
    Save the given user dictionary into USERS_DB_FILE.

    The function also injects a "_meta" section with the given group_seed so
    That the file is self-describing and can be reused later by the assignment script.

    :param users_dict: Dictionary mapping username -> user data dict.
    :param group_seed: Seed string (GROUP_SEED from config.py).
    :return: None
    """
    data_to_save = dict(users_dict)
    data_to_save["_meta"] = {"group_seed": group_seed}
    with open(USERS_DB_FILE, "w") as f:
        json.dump(data_to_save, f, indent=4)
