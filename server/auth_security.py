def generate_salt(length: int = 16) -> str:
    """
    Generate a cryptographically secure random salt.

    The salt is returned as a hex string if length 2 * length bytes
    :param length:  Number of random bytes before hex encoding (default 16 bytes).
    :return: Hex encoded salt string.
    """
    # Return as hex random crypto
    return os.urandom(length).hex()

def hash_password_sha256_salt(password: str, salt: str) -> str:
    """
    Hash a password using SHA-256 with a per-user salt and global PEPPER.

    The hash is computed over:
        sha256 (salt || (password + PEPPER))

    :param password: Plain text password.
    :param salt:  Hex string salt stored per user.
    :return: Hex string SHA256 digset.
    """
    to_hash = (password + PEPPER).encode("utf-8")
    salted = salt.encode("utf-8") + to_hash
    return hashlib.sha256(salted).hexdigest()

def hash_password_bcrypt(password: str) -> str:
    """
    Hash a password with bcrypt, using a random salt generated by bcrypt.gensaly().

    Important:
    - In bcrypt, the salt is already embedded inside the hash string.
    - We still append the global PEPPER to the password before hashing.

    :param password: Plain-text password.
    :return: Bcrypt hash as UTF-8 string (to be stored in DB).
    """
    # The function hashpw receives bytes and return bytes
    to_hash = (password + PEPPER).encode("utf-8")
    hashed = bcrypt.hashpw(to_hash, bcrypt.gensalt(rounds=12)).decode("utf-8")
    return hashed

def hash_password_argon2id(password: str) ->str:
    """
    Hash a password using Argon2id via argon2-cffi PasswordHasher.

    Argon2id includes its own random salt inside the encoded hash string.
    As with ither modes, PEPPER is appended to the password.

    :param password: Plain-text password
    :return: Argon2id encoded hash string.
    """
    to_hash = (password + PEPPER).encode("utf-8")
    return argon2_hasher.hash(to_hash)

def hash_password(password: str, salt: str,mode: str) -> str:
    """
    Dispatch hashing according to the given hash mode.

    This function is used by generate_users.py and server.py,
    so they don't need to know the implementation details of each hash.

    :param password: Plain-text password
    :param salt: Salt string (used only for SHA256)
    :param mode: One of SUPPORTED_HASH_MODE
    :return: Encoded hash string.
    :raises ValueError: If an unsupported mode is passed.
    """

    match mode:
        case "sha256_salt":
            return hash_password_sha256_salt(password, salt)
        case "bcrypt":
            return hash_password_bcrypt(password)
        case "argon2id":
            return hash_password_argon2id(password)
        case _:
            raise ValueError(f"unsupported HASH_MODE: {mode}")
