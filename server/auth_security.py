def get_user_hash_mode(user:dict)-> str:
    """
    Extract the hash_mode from a user record.

    :param user: User dictionary from the DB.
    :return: hash mode string, or "unknown" if missing.
    """
    return user.get("hash_mode","unknown")

def is_hash_mode_compatible(user: dict, runtime_mode: str)-> bool:
    """
    Check if the stored hash for a user matches the current run time HASH_MODE.

    This protects against trying to verify a user that was hashed with
    a different mode than the one the server currently uses.

    :param user: User dictionary from the DB.
    :param runtime_mode: Mode that the server is configured with(HASH_MODE).
    :return: True if they match, False otherwise.
    """
    return get_user_hash_mode(user) == runtime_mode

def verify_password(password: str, user: dict) -> bool:
    """
    Verify a candidate password against the stored hash for a user.

    The function:
        1. Reads the user's stored hash and salt.
        2. Checks the user's hash mode.
        3. Recomputes the hash using the same mode (including PEPPER)
        4. Compares or verifies using the appropriate library call.

    Supported modes:
        - "sha256_salt": recompute and compare hex digest.
        - "bcrypt": use bcrypt.checkpw.
        - "argon2id": use argon2_hasher.verify.

    Any verification error or unsupported mode results in False.

    :param password: Plain-text password is provided in the login request.
    :param user: User dictionary from the DB
    :return: True if the password is correct, False otherwise.
    """
    stored_hash = user["password_hash"]
    salt = user["salt"]
    user_mode = user.get("hash_mode", "unknown")

    match user_mode:

        case "sha256_salt":
            candidate = hash_password_sha256_salt(password, salt)
            return candidate == stored_hash
        case "bcrypt":
            try:
                to_check = (password + PEPPER).encode("utf-8")
                return bcrypt.checkpw(to_check, stored_hash.encode("utf-8"))
            except ValueError:
                return False
        case "argon2id":
            try:
                to_check = password + PEPPER
                return argon2_hasher.verify(stored_hash, to_check)
            except argon2_exceptions.VerifyMismatchError:
                # password does not match.
                return False
            except argon2_exceptions.VerificationError:
                # Any other problem
                return False
        case _:
            # Unsupported or missing hash_mode -> treat as failure.
                return False