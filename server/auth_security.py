"""
auth_security.py

Security helpers for the login system:
* Password hashing (shat256+salt, bcrypt, argon2id) with optional global PEPPER.
* TOTP (Time-based One Time Password) secret genartion & verification.
* User DB load/save helpers (users_db.json).
* Hash mode compatibility helpers.

This module is used by server.py to:
- Hash passwords on registration/user generation.
- Verify passwords on login.
- Manage TOTP secrets for users.
"""
