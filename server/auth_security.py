def generate_totp_secret() ->str:
    """
    Generates a new TOTP secret for a user.

    The secret is returned as a BASE32 string.
    This value should be stored once per user
    """

    return  pyotp.random_base32()

def verify_totp_code(secret: str, code: str) ->bool:
    """
    Verify TOTP code provided by the user.

    The same shared secret must be used which was generated by
    generate_totp_secret(),
    valid_window=1 allows a small clock drift (previous and next 30-second window)

    :param secret: Shared BASE32 secret for the user.
    :param code:  TOTP code as string
    :return: True if the code is valid in the allowed time window,
             False otherwise
    """

    totp = pyotp.TOTP(secret)
    return totp.verify(code, valid_window=1)

