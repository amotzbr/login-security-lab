# Argon2 hasher instance used for all argon2id operations.
# Parameters:
#       time_cost   - number of iiterations (CPU work factor)
#       memory_cost - memory usage
#       parallelism - number of threads used by Argon2
#       hash_len    - length of resulting hash
#       salt_len    - salt length in bytes
#       type        - Argon2Type.ID (Argon2id variant: resistant to GPU/ASIC attacks)
argon2_hasher = PasswordHasher(
    time_cost=1,
    memory_cost=64 * 1024, #64MB
    parallelism=1,
    hash_len=32,
    salt_len=16,
    type=Argon2Type.ID
)
